import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const contentDir = path.join(root, "content", "blog");
const outputFile = path.join(root, "apps", "web", ".vinext", "generated-posts.ts");
const files = fs.existsSync(contentDir)
  ? fs.readdirSync(contentDir).filter((file) => file.endsWith(".md")).sort()
  : [];
const posts = files.map((filename) => {
  const { data, content } = matter(fs.readFileSync(path.join(contentDir, filename), "utf8"));
  return { slug: filename.replace(/\.md$/, ""), frontmatter: data, content: content.trim() };
});
const source = "// Generated by scripts/generate-blog-data.mjs. Do not edit manually.\n" +
  "type GeneratedBlogPost = { slug: string; frontmatter: unknown; content: string };\n" +
  `export const generatedBlogPosts: GeneratedBlogPost[] = ${JSON.stringify(posts, null, 2)};\n`;
fs.writeFileSync(outputFile, source, "utf8");
console.log(`[blog] Generated ${posts.length} post(s)`);
